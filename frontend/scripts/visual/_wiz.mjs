import { chromium } from 'playwright-core'
import { SESSIONS } from './sessions.mjs'
const b = await chromium.launch({ executablePath: '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser', headless: true })
const vw = Number(process.argv[2] || 375)
const ctx = await b.newContext({ viewport: { width: vw, height: 812 } })
await ctx.addInitScript(([k, v]) => localStorage.setItem(k, v), ['saksi:session-v2', JSON.stringify(SESSIONS.kades)])
const p = await ctx.newPage()
await p.goto('http://localhost:3199/dashboard/kontrak/baru', { waitUntil: 'networkidle' })
await p.getByRole('button', { name: /Pengadaan/ }).first().click()
await p.getByRole('button', { name: 'Lanjut' }).click()
await p.locator('label', { hasText: /CV Maju Bersama/ }).first().click()
await p.getByRole('button', { name: 'Lanjut' }).click()
await p.locator('textarea').first().fill('Pengadaan 12 unit lampu jalan tenaga surya untuk Dusun Krajan')
await p.locator('input:not([type=date])').first().fill('52000000')
await p.locator('input[type=date]').first().fill('2027-03-01')
await p.getByRole('button', { name: /Susun draf/ }).click()
await p.waitForTimeout(2500)
await p.getByRole('button', { name: 'Lanjut' }).click()
await p.waitForTimeout(500)
console.log('step label:', await p.locator('h2', { hasText: 'Pratinjau surat' }).count(), 'canvas', await p.locator('canvas').count())
// draw a signature
const box = await p.locator('canvas').boundingBox()
await p.mouse.move(box.x + box.width * 0.15, box.y + box.height * 0.6)
await p.mouse.down()
for (let i = 0; i <= 20; i++) await p.mouse.move(box.x + box.width * (0.15 + i * 0.035), box.y + box.height * (0.6 - 0.35 * Math.sin(i / 3)))
await p.mouse.up()
await p.getByRole('button', { name: /Bubuhkan e-meterai/ }).click()
await p.waitForTimeout(500)
console.log('overflowX', await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'meterai text', await p.getByText(/No\. SIM-10000/).count())
await p.getByRole('heading', { name: 'Pratinjau surat' }).scrollIntoViewIfNeeded()
await p.screenshot({ path: `/tmp/wiz-${process.argv[2] || 375}.png`, fullPage: true })
await p.getByRole('button', { name: /Simpan sebagai draf/ }).click()
await p.waitForURL(/dashboard\/kontrak\/SKS/, { timeout: 15000 })
await p.goto(p.url() + '?tab=tanda-tangan', { waitUntil: 'networkidle' })
console.log('saved at', p.url(), 'signature img', await p.locator('img[alt^="Tanda tangan"]').count(), 'meterai', await p.getByText(/No\. SIM-10000/).count())
await b.close()
